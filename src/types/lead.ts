/** Источник заявки на сайте. */
export type LeadKind = "evaluate" | "courier" | "request";

/** Данные заявки перед отправкой на API. */
export type LeadPayload = {
  kind: LeadKind;
  phone: string;
  /** Название услуги — только для заявки из карточки. */
  serviceTitle?: string;
  /** Фото вещи — только для оценки. */
  photos?: File[];
};
